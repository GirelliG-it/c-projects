# for-loop
#
# Key Differences:
#    range(start, stop): Starts at 1 and stops before 11 (so it includes numbers 1 through 10).
#
#    Automatic Increment:
#    The for loop automatically increments i on each iteration, so you don't need i += 1.
#
#    += Operator:
#    If you ever need to manually add to a variable outside a simple loop, the operator order is += (e.g., x += 1), not =+.


for i in range(1, 11):
    print(i)
